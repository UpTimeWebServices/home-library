#!/usr/bin/env python3
"""Turn Home_Library_Catalog.xlsx into db/seed.sql for D1.

Usage:  python3 scripts/import_catalog.py path/to/Home_Library_Catalog.xlsx > db/seed.sql

- One `works` row per title+author; each spreadsheet row becomes a `copies` row
  (duplicates share a work).
- Copies get their CURRENT location (Room/Case/Shelf/Position) as shelf_id and the
  re-file plan's destination (Dest. Room/Case/Shelf) as planned_shelf_id.
- Shelves come from the Destination Map (planned shelves, with width + section ranges)
  plus any current locations not in the plan (Overflow 1-5, nightstands), plus the
  guest room stack (unlimited overflow).
"""
import re
import sys

import openpyxl

NO_RECOMMEND = {"Children's", "Graphic Novels/Manga"}
ARTICLES = re.compile(r"^(the|a|an)\s+", re.I)


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v) if isinstance(v, float) and v != int(v) else str(int(v))
    return "'" + str(v).replace("'", "''") + "'"


def clean(v):
    if v is None:
        return None
    s = str(v).strip()
    return s or None


def display_author(author_sort):
    """'Gaiman, Neil; Pratchett, Terry' -> 'Neil Gaiman & Terry Pratchett'."""
    if not author_sort:
        return None
    out = []
    for part in author_sort.split(";"):
        part = part.strip()
        m = re.match(r"^([^,]+),\s*(.+?)(\s*\(ed\.\))?$", part)
        if m and m.group(2):
            out.append(f"{m.group(2)} {m.group(1)}{m.group(3) or ''}")
        else:
            out.append(part)
    return " & ".join(out)


def label(v):
    if isinstance(v, float) and v == int(v):
        v = int(v)
    return str(v).strip() if v is not None else None


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    out = ["-- Generated by scripts/import_catalog.py — do not edit by hand", "PRAGMA foreign_keys = OFF;"]

    # ---- sections ------------------------------------------------------
    inches = {}
    cap = list(wb["Shelf Capacity"].iter_rows(values_only=True))
    in_space = False
    for r in cap:
        if r[0] == "Section" and r[2] == "Inches per book":
            in_space = True
            continue
        if in_space:
            if r[0] in (None, "Total"):
                break
            inches[r[0]] = r[2]

    sections = []
    for r in wb["Rules & Legend"].iter_rows(values_only=True):
        m = re.match(r"^(\d+)\.\s+(.+)$", str(r[0] or ""))
        if m:
            sections.append((int(m.group(1)), m.group(2).strip(), clean(r[1])))
    names = {n for _, n, _ in sections}
    # Rules list "Witchy (Parlor)" etc.; catalog uses the same names.
    for order, name, note in sections:
        out.append(
            "INSERT INTO sections (name, rule_order, rule_note, inches_per_book, recommend) VALUES "
            f"({q(name)}, {order}, {q(note)}, {q(inches.get(name, 1.1))}, {0 if name in NO_RECOMMEND else 1});"
        )

    # ---- shelves -------------------------------------------------------
    shelves = {}  # (room, case, shelf) -> id
    sort = 0

    def add_shelf(room, case, shelf, width=None, section=None, first=None, last=None, overflow=0):
        nonlocal sort
        key = (room, case, shelf)
        if key in shelves:
            return shelves[key]
        sort += 1
        sid = len(shelves) + 1
        shelves[key] = sid
        out.append(
            "INSERT INTO shelves (id, room, case_label, shelf_label, width_in, section, first_author, last_author, sort_order, is_overflow) VALUES "
            f"({sid}, {q(room)}, {q(case)}, {q(shelf)}, {q(width)}, {q(section)}, {q(first)}, {q(last)}, {sort}, {overflow});"
        )
        return sid

    for r in list(wb["Destination Map"].iter_rows(min_row=2, values_only=True)):
        if not r[1]:
            continue
        secs = [s.strip() for s in str(r[8] or "").split(",") if s.strip()]
        add_shelf(r[1], label(r[2]), label(r[3]), r[4], secs[0] if secs and secs[0] in names else None, clean(r[9]), clean(r[10]))

    rows = [r for r in wb["Catalog"].iter_rows(min_row=2, values_only=True) if r[0]]
    # current locations not in the plan (Overflow 1-5, nightstands, ...)
    for r in sorted({(r[5], label(r[6]), label(r[7] or 1)) for r in rows if r[5]}, key=str):
        add_shelf(*r)
    add_shelf("Guest Room", "Dresser", "Stack", None, None, None, None, 1)

    # ---- series --------------------------------------------------------
    series = {}
    for r in rows:
        s = clean(r[2])
        if s and s not in series:
            series[s] = len(series) + 1
            out.append(f"INSERT INTO series (id, name) VALUES ({series[s]}, {q(s)});")

    # ---- works + copies ------------------------------------------------
    works = {}
    copy_id = 0
    for r in rows:
        (title, author, ser, ser_no, section, room, case, shelf, pos,
         d_room, d_case, d_shelf, flags, confidence, confirmed, notes) = r[:16]
        title = clean(title)
        author = clean(author)
        key = (title.lower(), (author or "").lower())
        flags = {f.strip() for f in str(flags or "").split(";") if f.strip()}
        if key not in works:
            wid = len(works) + 1
            works[key] = wid
            sort_title = ARTICLES.sub("", title)
            out.append(
                "INSERT INTO works (id, title, sort_title, author, author_sort, series_id, series_pos, section, notes, created_by) VALUES "
                f"({wid}, {q(title)}, {q(sort_title)}, {q(display_author(author))}, {q(author)}, "
                f"{q(series.get(clean(ser)))}, {q(ser_no)}, {q(section if section in names else None)}, {q(clean(notes))}, 'import');"
            )
        cur = shelves.get((room, label(case), label(shelf or 1))) if room else None
        plan = shelves.get((d_room, label(d_case), label(d_shelf))) if d_room and d_shelf else None
        special = "confirmed" if "Special" in flags else ("suspected" if "Special?" in flags else "none")
        copy_id += 1
        out.append(
            "INSERT INTO copies (id, work_id, shelf_id, shelf_pos, planned_shelf_id, special, bedroom_flag, confidence, notes, source, added_by) VALUES "
            f"({copy_id}, {works[key]}, {q(cur)}, {q(pos)}, {q(plan)}, {q(special)}, {1 if 'Bedroom?' in flags else 0}, "
            f"{q(confidence)}, NULL, 'import', 'import');"
        )

    out.append("PRAGMA foreign_keys = ON;")
    print("\n".join(out))
    print(f"-- {len(works)} works, {copy_id} copies, {len(shelves)} shelves, {len(series)} series", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
